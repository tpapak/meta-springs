suppressMessages(library(netmeta))
TE <- c(1.0,1.6, 2.0,2.6, 0.8,1.4)
seTE <- rep(sqrt(0.08), 6)
t1 <- c("A","A","A","A","B","B"); t2 <- c("B","B","C","C","C","C"); st <- paste0("S",1:6)
nm <- netmeta(TE,seTE,t1,t2,st,sm="MD",reference.group="A", method.tau="REML")
print(nm$tau2)
print(nm$TE.random["A",])
nmml <- netmeta(TE,seTE,t1,t2,st,sm="MD",reference.group="A", method.tau="ML")
cat("ML tau2=", nmml$tau2, "\n")
nmdl <- netmeta(TE,seTE,t1,t2,st,sm="MD",reference.group="A")
cat("DL tau2=", nmdl$tau2, "\n")
